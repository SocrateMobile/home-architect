const pluralRules = new Map<Lang, Intl.PluralRules | null>();

/** Catégorie de pluriel d'un nombre dans la langue courante (en français, 0 et 1 sont au singulier). */
function pluralCategory(count: number): 'one' | 'other' {
  const lang = getLanguage();
  if (!pluralRules.has(lang)) {
    try {
      pluralRules.set(lang, new Intl.PluralRules(lang === 'fr' ? 'fr-FR' : 'en-US'));
    } catch {
      pluralRules.set(lang, null);
    }
  }
  const rules = pluralRules.get(lang);
  if (rules) return rules.select(count) === 'one' ? 'one' : 'other';
  return count === 1 || (lang === 'fr' && count === 0) ? 'one' : 'other';
}

/**
 * Texte qui dépend d'un nombre : clé `<key>_one` ou `<key>_other` selon la langue courante.
 * Le marqueur `{count}` reçoit le nombre formaté ; les autres paramètres sont interpolés tels quels.
 */
export function localizeCount(key: string, count: number, params: Record<string, string | number> = {}): string {
  return localize(`${key}_${pluralCategory(count)}`, { ...params, count: formatNumber(count) });
}
