/**
 * Traductions d'une clé de l'espace dans toutes les langues : sert à reconnaître une valeur par
 * défaut enregistrée dans une autre langue que la langue courante (nom de meuble, « Pièce »…).
 */
export function geometryTranslations(key: string): string[] {
  return Object.values(dictionaries)
    .map(dict => dict[key])
    .filter((value): value is string => typeof value === 'string');
}
